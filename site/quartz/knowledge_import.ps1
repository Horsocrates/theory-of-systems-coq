# Имена и заголовки без нумерации «01/02» и без «Глава N.» — решение автора 2026-07-21 (сайт-библиотека: темы, не главы).

function Convert-Chapter {
  param([string]$srcPath, [string]$dstPath, [string]$title, [string]$desc,
        [string]$bottom, [bool]$stripComment, [string]$alias)
  $text = [System.IO.File]::ReadAllText($srcPath, $enc)
  if ($stripComment) {
    # служебная шапка-комментарий (метод, внутренние пометки) — не для сайта
    $text = [regex]::Replace($text, '^\s*<!--[\s\S]*?-->\s*', '')
  }
  # H1-заголовки источника (Часть/Глава) дублируют title страницы — убрать
  $lines = $text -split "`r?`n"
  $kept = New-Object System.Collections.Generic.List[string]
  foreach ($ln in $lines) {
    if ($ln -match '^# ') { continue }
    $kept.Add($ln)
  }
  $body = ($kept -join "`n").Trim()
  $al = if ($alias) { "aliases:`n  - $alias`n" } else { "" }
  $fm = "---`ntitle: $title`n" + $al + "description: `"$desc`"`n---`n`n"
  [System.IO.File]::WriteAllText($dstPath, $fm + $body + "`n`n---`n`n" + $bottom + "`n", $enc)
}

# Глава 9 (сборка «Теория Знания») — в Логику
