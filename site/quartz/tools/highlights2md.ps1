# highlights2md.ps1 - generate the "Избранные результаты" block from HIGHLIGHTS vitrina lines.
# Reads a source .md whose entries carry a  <!-- ... theme="..." level="..." part="..." cost="..." show="..." support="..." -->
# line plus one vitrina sentence, emits a theme-grouped block, and (optionally) injects it between
# <!-- HL:BEGIN --> / <!-- HL:END --> markers in a target page (like catalog2md.ps1).
# Pure ASCII on purpose: Cyrillic lives only in the DATA it reads/writes, so this .ps1 needs no BOM.
param(
  [string]$Source,
  [string]$IndexOut = '',
  [string]$Inject = '',
  # -NoMeta: print only the part link after each line; level and cost stay in the
  # source (they belong on the Formalization page, decision of 2026-10-17)
  [switch]$NoMeta,
  # -Formal: emit the table "result | level | part | cost | support in code" for the Formalization
  # page, between HLF markers; the header row is read from the source:
  #   <!-- FORMAL head="col1|col2|col3|col4|col5" -->
  [switch]$Formal
)

$D  = [string][char]0x00B7          # middle-dot separator
if ($Formal) {
  $B0 = '<!-- HLF:BEGIN (generated by tools/highlights2md.ps1 -Formal - do not edit by hand) -->'
  $E0 = '<!-- HLF:END -->'
  $K0 = '<!-- HLF:BEGIN'
} else {
  $B0 = '<!-- HL:BEGIN (generated by tools/highlights2md.ps1 - do not edit by hand) -->'
  $E0 = '<!-- HL:END -->'
  $K0 = '<!-- HL:BEGIN'
}
$noBom = New-Object System.Text.UTF8Encoding($false)

$raw = [System.IO.File]::ReadAllText($Source, [System.Text.Encoding]::UTF8) -replace "`r`n","`n"
$blocks = [regex]::Split($raw, '(?m)^(?=## H\d)')

$entries = New-Object System.Collections.Generic.List[object]
foreach ($b in $blocks) {
  if ($b -notmatch '(?m)^## H\d') { continue }
  if ($b -notmatch 'theme="')     { continue }
  $theme = ([regex]::Match($b,'theme="([^"]*)"')).Groups[1].Value
  $level = ([regex]::Match($b,'level="([^"]*)"')).Groups[1].Value
  $part  = ([regex]::Match($b,'part="([^"]*)"')).Groups[1].Value
  $cost  = ([regex]::Match($b,'cost="([^"]*)"')).Groups[1].Value
  $show  = ([regex]::Match($b,'show="([^"]*)"')).Groups[1].Value
  $supp  = ([regex]::Match($b,'support="([^"]*)"')).Groups[1].Value
  $vit = ''
  $after = $false
  foreach ($ln in ($b -split "`n")) {
    if (-not $after) { if ($ln -match 'theme="') { $after = $true }; continue }
    if ($ln.Trim() -ne '') { $vit = $ln.Trim(); break }
  }
  # result title = the bold head of the vitrina sentence, without its closing period or colon
  $mt = [regex]::Match($vit, '\*\*(.+?)\*\*')
  $title = if ($mt.Success) { $mt.Groups[1].Value } else { $vit }
  $title = $title -replace '[.:]$', ''
  $entries.Add([pscustomobject]@{ theme=$theme; level=$level; part=$part; cost=$cost; show=$show; support=$supp; vit=$vit; title=$title })
}

# entries shown in the showcase (show contains 'index'), first-seen theme order
$idx = @($entries | Where-Object { $_.show -match 'index' })
$order = @(); foreach ($e in $idx) { if ($order -notcontains $e.theme) { $order += $e.theme } }

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add($B0); $lines.Add('')
if ($Formal) {
  $head = ([regex]::Match($raw, '<!-- FORMAL head="([^"]*)"')).Groups[1].Value
  if ($head -eq '') { $head = 'Result|Level|Part|Cost|Support' }
  $cols = @($head -split '\|' | ForEach-Object { $_.Trim() })
  $lines.Add('| ' + ($cols -join ' | ') + ' |')
  $lines.Add('|' + (($cols | ForEach-Object { '---' }) -join '|') + '|')
  foreach ($t in $order) {
    foreach ($e in ($idx | Where-Object { $_.theme -eq $t })) {
      $cells = @($e.title, $e.level, ($e.part -replace '\|', '\|'), $e.cost, $e.support)
      $lines.Add('| ' + ($cells -join ' | ') + ' |')
    }
  }
  $lines.Add('')
} else {
  foreach ($t in $order) {
    $lines.Add('**' + $t + '.**'); $lines.Add('')
    foreach ($e in ($idx | Where-Object { $_.theme -eq $t })) {
      if ($NoMeta) { $meta = $e.part }
      else { $meta = $e.level + ' ' + $D + ' ' + $e.part + ' ' + $D + ' ' + $e.cost }
      $lines.Add('- ' + $e.vit + ' *(' + $meta + ')*')
    }
    $lines.Add('')
  }
}
$lines.Add($E0)
$blockLF = [string]::Join("`n", $lines)

if ($IndexOut -ne '') { [System.IO.File]::WriteAllText($IndexOut, $blockLF, $noBom) }

if ($Inject -ne '') {
  $tb = [System.IO.File]::ReadAllBytes($Inject)
  $thasBom = ($tb.Length -ge 3 -and $tb[0] -eq 0xEF -and $tb[1] -eq 0xBB -and $tb[2] -eq 0xBF)
  $s0 = if ($thasBom) { 3 } else { 0 }
  $tgt = $noBom.GetString($tb, $s0, $tb.Length - $s0)
  $nl = if ($tgt -match "`r`n") { "`r`n" } else { "`n" }
  $block = $blockLF -replace "`n", $nl
  $bi = $tgt.IndexOf($K0)
  $ei = $tgt.IndexOf($E0)
  if ($bi -ge 0 -and $ei -gt $bi) {
    $new = $tgt.Substring(0, $bi) + $block + $tgt.Substring($ei + $E0.Length)
    [System.IO.File]::WriteAllText($Inject, $new, (New-Object System.Text.UTF8Encoding($thasBom)))
    Write-Output ("injected: " + $Inject + " (bom=" + $thasBom + ")")
  } else {
    Write-Output "MARKERS NOT FOUND in inject target"
  }
}

Write-Output ("entries=" + $entries.Count + " index=" + $idx.Count)
