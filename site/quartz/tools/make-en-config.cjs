// make-en-config.cjs — генерирует quartz.config.en.yaml (английская сборка в /en/) из quartz.config.yaml.
// Два конфига не расходятся: английский — это русский плюс оверлей ниже.
//   node tools/make-en-config.cjs [baseUrl]        (по умолчанию localhost:8080/en)
// В CI baseUrl остаётся localhost:8080/en: web_translit.py сам меняет localhost:8080 на домен.
const fs = require('fs');
const path = require('path');
const YAML = require('yaml');

const root = path.resolve(__dirname, '..');
const src = path.join(root, 'quartz.config.yaml');
const out = path.join(root, 'quartz.config.en.yaml');
const baseUrl = process.argv[2] || 'localhost:8080/en';

const cfg = YAML.parse(fs.readFileSync(src, 'utf8'));
const c = cfg.configuration;
c.pageTitle = 'The Path of Wisdom';
c.locale = 'en-US';
c.baseUrl = baseUrl;

const plugin = name => cfg.plugins.find(p => p.source === `github:quartz-community/${name}`);

// Проводник: веса и правила — по английским сегментам (зеркало русских весов).
const explorer = plugin('explorer');
if (explorer) {
  explorer.options.sortFn = `(a, b) => {
  const w = { "path-of-wisdom": 0.5, "charter": 1, "code-of-ethics": 1.5, "library": 2, "contacts": 99, "branches": 10, "logic": 51, "metaphysics": 52, "theory-of-systems": 53, "epistemology": 54, "ethics": 55, "social-systems": 55.5, "architecture-of-reasoning": 56, "mathematics": 57, "question": 43, "domains": 44, "fallacy-catalog": 90, "paradox-catalog": 91, "formalization": 14, "what-is-not-and-cannot-be": 15, "identity": 71, "non-contradiction": 72, "excluded-middle": 73, "sufficient-reason": 74, "order": 75, "philosophy": 76 };
  const wa = w[a.slugSegment] ?? 50;
  const wb = w[b.slugSegment] ?? 50;
  if (wa !== wb) return wa - wb;
  if ((!a.isFolder && !b.isFolder) || (a.isFolder && b.isFolder)) {
    return (a.slugSegment || "").localeCompare(b.slugSegment || "", undefined, { numeric: true, sensitivity: "base" });
  }
  return a.isFolder ? -1 : 1;
}
`;
  explorer.options.filterFn = '(node) => node.slugSegment !== "tags"\n';
  explorer.options.mapFn = '(node) => { if (node.slugSegment === "mathematics" || node.slugSegment === "epistemology") { node.isFolder = false; } return node; }\n';
}

// CNAME пишет только русская сборка.
const cname = plugin('cname');
if (cname) cname.enabled = false;

// Блок свойств на английских страницах не показываем (служебные поля перевода).
const props = plugin('note-properties');
if (props && props.options) props.options.hidePropertiesView = true;

const header = '# GENERATED by tools/make-en-config.cjs from quartz.config.yaml — do not edit by hand.\n';
fs.writeFileSync(out, header + YAML.stringify(cfg, { lineWidth: 0 }), 'utf8');
console.log(`written ${path.relative(root, out)} (baseUrl ${baseUrl})`);
