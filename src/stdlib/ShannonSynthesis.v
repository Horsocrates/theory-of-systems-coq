From Stdlib Require Import QArith Lqa Lia.
From ToS Require Import stdlib.DyadicBits.
Open Scope Q_scope.

(* --- Локальная реплика бинарной энтропии (Паде-log), тождественно MajorizationSchur.v --- *)
Definition ln_pade (x : Q) : Q := 2 * (x - 1) / (x + 1).
Definition S2 (a : Q) : Q := -(a * ln_pade a + (1 - a) * ln_pade (1 - a)).

(** Значение на равновероятном — максимум бинарной энтропии (в Паде-нормировке). *)
Lemma S2_at_half : S2 (1#2) == 2#3.
Proof. unfold S2, ln_pade. vm_compute. reflexivity. Qed.

(** Значения в несимметричных точках. *)
Lemma S2_at_34 : S2 (3#4) == 18#35.
Proof. unfold S2, ln_pade. vm_compute. reflexivity. Qed.

Lemma S2_at_13 : S2 (1#3) == 3#5.
Proof. unfold S2, ln_pade. vm_compute. reflexivity. Qed.

(** ★ Бинарная энтропия пикует на равновероятном: несимметричные точки строго ниже. *)
Lemma S2_peaks_34 : S2 (3#4) < S2 (1#2).
Proof. rewrite S2_at_34, S2_at_half. lra. Qed.

Lemma S2_peaks_13 : S2 (1#3) < S2 (1#2).
Proof. rewrite S2_at_13, S2_at_half. lra. Qed.

(* ===================================================================== *)
(*  КАПСТОУН: информация = структурная величина, с разрезом Element/role-limit *)
(* ===================================================================== *)

(** ★ Одно утверждение, собирающее три грани информации как структурной величины:
    (1) бинарная энтропия пикует на равновероятном (максимум неопределённости);
    (2) ДИАДИЧЕСКОЕ точно: 2^3 = 8 — k бит кодируют 2^k состояний (Element);
    (3) ТРИТОВОЕ — role-limit: log2 3 иррационально, нет конечного битового представления. *)
Theorem information_is_structural_quantity :
  (S2 (3#4) < S2 (1#2) /\ S2 (1#3) < S2 (1#2))
  /\ Nat.pow 2 3 = 8%nat
  /\ ~ (exists a b : nat, (1 <= b)%nat /\ Nat.pow 2 a = Nat.pow 3 b).
Proof.
  exact (conj (conj S2_peaks_34 S2_peaks_13) (conj dyadic_exact log2_3_irrational)).
Qed.

Print Assumptions S2_peaks_34.
Print Assumptions information_is_structural_quantity.

