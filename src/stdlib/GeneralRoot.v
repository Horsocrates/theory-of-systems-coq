From Stdlib Require Import ZArith Znumtheory Lia.

Open Scope Z_scope.

(* ===================================================================== *)
(*  Integer k-th power (own Fixpoint, to keep proofs definitional)         *)
(* ===================================================================== *)

Fixpoint zpow (a : Z) (k : nat) : Z :=
  match k with
  | O => 1
  | S k' => a * zpow a k'
  end.

(** 1 to any power is 1. *)
Lemma zpow_one : forall k : nat, zpow 1 k = 1.
Proof. induction k as [| k IH]; [ reflexivity | simpl; rewrite IH; reflexivity ]. Qed.

(* ===================================================================== *)
(*  Coprimality is preserved under the k-th power (induction on k)         *)
(* ===================================================================== *)

(** Anything is coprime to 1. *)
Lemma rel_prime_b_1 : forall b : Z, rel_prime b 1.
Proof.
  intros b. apply Zis_gcd_intro.
  - apply Z.divide_1_l.
  - apply Z.divide_1_l.
  - intros x _ Hx1. exact Hx1.
Qed.

(** ★ The degree-uniformity engine: if b is coprime to a, it is coprime to a^k for EVERY k.
    One induction step (a^{S k} = a·a^k, rel_prime_mult) lifts coprimality to all degrees. *)
Lemma rel_prime_zpow : forall (a b : Z) (k : nat),
  rel_prime b a -> rel_prime b (zpow a k).
Proof.
  intros a b k H. induction k as [| k IH].
  - simpl. apply rel_prime_b_1.
  - simpl. apply rel_prime_mult; [ exact H | exact IH ].
Qed.

(** b divides b^{k+1}. *)
Lemma b_div_zpow_succ : forall (b : Z) (k : nat), (b | zpow b (S k)).
Proof. intros b k. simpl. exists (zpow b k). ring. Qed.

(* ===================================================================== *)
(*  THE CAPSTONE: a reduced fraction with integer k-th power is integer    *)
(* ===================================================================== *)

(** ★ For every k, a reduced fraction a/b (gcd a b = 1, b > 0) whose (k+1)-th power is an
    integer n (a^{k+1} = n·b^{k+1}) has denominator b = 1.  ONE engine for all degrees. *)
Lemma reduced_kth_power_integer : forall (a b n : Z) (k : nat),
  0 < b -> Z.gcd a b = 1 -> zpow a (S k) = n * zpow b (S k) -> b = 1.
Proof.
  intros a b n k Hpos Hcop Heq.
  assert (Hdivb : (b | zpow b (S k))) by apply b_div_zpow_succ.
  assert (Hdiv : (b | zpow a (S k))).
  { rewrite Heq. apply Z.divide_mul_r. exact Hdivb. }
  assert (Hrp_ba : rel_prime b a).
  { apply rel_prime_sym. red. rewrite <- Hcop. apply Zgcd_is_gcd. }
  assert (Hrp : rel_prime b (zpow a (S k))) by (apply rel_prime_zpow; exact Hrp_ba).
  assert (Hb1 : (b | 1)).
  { destruct Hrp as [_ _ Hg]. apply Hg; [ apply Z.divide_refl | exact Hdiv ]. }
  pose proof (Z.divide_pos_le b 1 ltac:(lia) Hb1) as Hle.
  lia.
Qed.

(** ★ Hence the perfect-k-th-power criterion: a reduced fraction whose (k+1)-th power is the
    integer n witnesses that n IS a perfect (k+1)-th power (n = a^{k+1}). *)
Lemma perfect_kth_power_criterion : forall (a b n : Z) (k : nat),
  0 < b -> Z.gcd a b = 1 -> zpow a (S k) = n * zpow b (S k) ->
  exists m : Z, n = zpow m (S k).
Proof.
  intros a b n k Hpos Hcop Heq.
  assert (Hb : b = 1) by (apply (reduced_kth_power_integer a b n k); assumption).
  exists a. rewrite Hb in Heq. rewrite zpow_one in Heq. lia.
Qed.

(* ===================================================================== *)
(*  The square / cube engines are the k = 2, 3 instances                   *)
(* ===================================================================== *)

(** ★ GeneralSqrt's engine recovered as the k=2 instance: the general theorem subsumes it. *)
Corollary square_engine_instance : forall a b n : Z,
  0 < b -> Z.gcd a b = 1 -> a * a = n * (b * b) -> b = 1.
Proof.
  intros a b n Hpos Hcop Heq.
  apply (reduced_kth_power_integer a b n 1%nat); try assumption.
  cbn [zpow].
  replace (a * (a * 1)) with (a * a) by ring.
  replace (n * (b * (b * 1))) with (n * (b * b)) by ring.
  exact Heq.
Qed.

(** GeneralCbrt's engine recovered as the k=3 instance. *)
Corollary cube_engine_instance : forall a b n : Z,
  0 < b -> Z.gcd a b = 1 -> a * a * a = n * (b * b * b) -> b = 1.
Proof.
  intros a b n Hpos Hcop Heq.
  apply (reduced_kth_power_integer a b n 2%nat); try assumption.
  cbn [zpow].
  replace (a * (a * (a * 1))) with (a * a * a) by ring.
  replace (n * (b * (b * (b * 1)))) with (n * (b * b * b)) by ring.
  exact Heq.
Qed.

