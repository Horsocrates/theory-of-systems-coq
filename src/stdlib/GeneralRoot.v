(** The degree-uniform finitization engine:
      (a) CAPSTONE — for EVERY k, a reduced fraction with integer (k+1)-th power is an integer
          (`reduced_kth_power_integer`), so such an n is a perfect (k+1)-th power
          (`perfect_kth_power_criterion`); degree-uniformity is a theorem via the induction
          `rel_prime_zpow`;
      (b) INSTANCES — the square (k=2) and cube (k=3) engines of GeneralSqrt/GeneralCbrt are
          recovered (`square_engine_instance`, `cube_engine_instance`). *)
Theorem general_root_synthesis :
  (forall (a b n : Z) (k : nat),
     0 < b -> Z.gcd a b = 1 -> zpow a (S k) = n * zpow b (S k) -> b = 1)
  /\ (forall (a b n : Z) (k : nat),
        0 < b -> Z.gcd a b = 1 -> zpow a (S k) = n * zpow b (S k) ->
        exists m : Z, n = zpow m (S k))
  /\ (forall a b n : Z, 0 < b -> Z.gcd a b = 1 -> a * a = n * (b * b) -> b = 1)
  /\ (forall a b n : Z, 0 < b -> Z.gcd a b = 1 -> a * a * a = n * (b * b * b) -> b = 1).
Proof.
  split; [ exact reduced_kth_power_integer | ].
  split; [ exact perfect_kth_power_criterion | ].
  split; [ exact square_engine_instance | exact cube_engine_instance ].
Qed.
