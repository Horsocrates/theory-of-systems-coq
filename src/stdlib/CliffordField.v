(** The field of definition of the Clifford group in one statement:
      (a) ℚ[√2] genuinely extends ℚ — √2 is named there (√2²=2) but irrational
          over ℚ (the role-limit, named-not-computed);
      (b) the ELEMENT extension ℚ[i] has i but NOT √2;
      (c) the ROLE-LIMIT extension ℚ[√2] has √2 but NOT i — the two are
          INCOMPARABLE, so the full Clifford group needs the compositum ℚ[ζ₈];
      (d) Hadamard lives on the role-limit (real) side: H²=I over ℚ[√2]. *)
Theorem clifford_field_synthesis :
  (req (rmul r2 r2) (2#1, 0) /\ ~ (exists q : Q, q * q == 2))
  /\ (geq (gmul gi gi) gn1 /\ ~ (exists g : GQ, geq (gmul g g) (2#1, 0)))
  /\ ~ (exists x : RQ, req (rmul x x) (-(1#1), 0))
  /\ rm_eq (rm_mul mH mH) rm_id.
Proof.
  split.
  { split; [ exact r2_is_sqrt2 | exact sqrt2_not_in_Q ]. }
  split.
  { split; [ exact gi_sq | exact no_gaussian_sqrt2 ]. }
  split; [ exact i_not_in_Qsqrt2 | exact mH_invol ].
Qed.
