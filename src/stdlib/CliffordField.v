From Stdlib Require Import QArith Qabs ZArith Lia Lqa.
From ToS Require Import analysis.Sqrt2Irrational.
Open Scope Q_scope.

(** Every rational square is non-negative (used for both cross-obstructions). *)
Lemma qsq_nonneg : forall q : Q, 0 <= q * q.
Proof.
  intro q. destruct (Qlt_le_dec q 0) as [Hlt | Hge].
  - assert (Hr : q * q == (- q) * (- q)) by ring.
    rewrite Hr. apply Qmult_le_0_compat; lra.
  - apply Qmult_le_0_compat; lra.
Qed.

(* ===================================================================== *)
(*  ℚ[√2] = (a, b) meaning a + b√2  — the ROLE-LIMIT (real) extension      *)
(*  multiplication uses (√2)² = 2                                          *)
(* ===================================================================== *)

Definition RQ : Type := (Q * Q)%type.
Definition radd (z w : RQ) : RQ := (fst z + fst w, snd z + snd w).
Definition rmul (z w : RQ) : RQ :=
  (fst z * fst w + 2 * (snd z * snd w), fst z * snd w + snd z * fst w).
Definition req (z w : RQ) : Prop := fst z == fst w /\ snd z == snd w.

Definition r0 : RQ := (0, 0).
Definition r1 : RQ := (1, 0).
Definition r2 : RQ := (0, 1).      (* the adjoined √2 *)

(** √2 is named in ℚ[√2]: the generator (0,1) squares to 2. *)
Lemma r2_is_sqrt2 : req (rmul r2 r2) (2#1, 0).
Proof. vm_compute; repeat split; reflexivity. Qed.

(** i ∉ ℚ[√2]: ℚ[√2] is a REAL field (every square ≥ 0), so nothing squares to −1.
    a + b√2 ⟹ (a+b√2)² = (a²+2b²) + 2ab√2, and a²+2b² ≥ 0 > −1. *)
Theorem i_not_in_Qsqrt2 : ~ (exists x : RQ, req (rmul x x) (-(1#1), 0)).
Proof.
  intros [[a b] H]. unfold req, rmul in H. cbn in H.
  destruct H as [H1 _].
  (* H1 : a*a + 2*(b*b) == -1 *)
  assert (Ha : 0 <= a * a) by apply qsq_nonneg.
  assert (Hb : 0 <= b * b) by apply qsq_nonneg.
  lra.
Qed.

(* ===================================================================== *)
(*  Hadamard lives on the role-limit side: H² = I over ℚ[√2]              *)
(* ===================================================================== *)

Definition RM2 : Type := (RQ * RQ * RQ * RQ)%type.   (* row-major (a b / c d) *)
Definition rm_id : RM2 := (r1, r0, r0, r1).

Definition s2  : RQ := (0, 1#2).        (* 1/√2 = √2/2 *)
Definition ns2 : RQ := (0, -(1#2)).     (* −1/√2 *)
Definition mH  : RM2 := (s2, s2, s2, ns2).   (* (1/√2)[[1,1],[1,−1]] *)

Definition rm_mul (M N : RM2) : RM2 :=
  let '(a,b,c,d) := M in
  let '(e,f,p,q) := N in
  (radd (rmul a e) (rmul b p),
   radd (rmul a f) (rmul b q),
   radd (rmul c e) (rmul d p),
   radd (rmul c f) (rmul d q)).

Definition rm_eq (M N : RM2) : Prop :=
  let '(a,b,c,d) := M in
  let '(e,f,p,q) := N in
  req a e /\ req b f /\ req c p /\ req d q.

(** H² = I: the Hadamard gate is an involution — finite order 2, but its field of
    definition ℚ[√2] is a ROLE-LIMIT extension (the 1/√2 = √2/2 entries). *)
Lemma mH_invol : rm_eq (rm_mul mH mH) rm_id.
Proof. vm_compute; repeat split; reflexivity. Qed.

(* ===================================================================== *)
(*  ℚ[i] = (a, b) meaning a + bi  — the ELEMENT extension (i²=−1)          *)
(* ===================================================================== *)

Definition GQ : Type := (Q * Q)%type.
Definition gmul (z w : GQ) : GQ :=
  (fst z * fst w - snd z * snd w, fst z * snd w + snd z * fst w).
Definition geq (z w : GQ) : Prop := fst z == fst w /\ snd z == snd w.
Definition gi  : GQ := (0, 1).        (* the imaginary unit *)
Definition gn1 : GQ := (-1, 0).       (* −1 *)

(** i² = −1: the Element extension ℚ[i] contains i (the Z₄ Element, recall ①). *)
Lemma gi_sq : geq (gmul gi gi) gn1.
Proof. vm_compute; repeat split; reflexivity. Qed.

(** √2 ∉ ℚ[i]: no Gaussian rational squares to 2.  a+bi ⟹ (a²−b²) + 2ab·i = 2 ⟹
    2ab=0 and a²−b²=2 ⟹ either a²=2 (no rational root, via √2) or b²=−2
    (impossible).  So the Element extension does NOT reach √2. *)
Theorem no_gaussian_sqrt2 : ~ (exists g : GQ, geq (gmul g g) (2#1, 0)).
Proof.
  intros [[a b] H]. unfold geq, gmul in H. cbn in H.
  destruct H as [Hre Him].
  (* Hre : a*a - b*b == 2 ;  Him : a*b + b*a == 0 *)
  assert (Hab : a * b == 0).
  { assert (Hdup : a * b + b * a == 2 * (a * b)) by ring. lra. }
  apply Qmult_integral in Hab. destruct Hab as [Ha0 | Hb0].
  - (* a = 0 ⟹ b² = −2, impossible *)
    assert (Haa : a * a == 0) by (rewrite Ha0; ring).
    assert (Hbb : b * b == -(2#1)) by lra.
    assert (Hnn : 0 <= b * b) by apply qsq_nonneg.
    lra.
  - (* b = 0 ⟹ a² = 2, no rational root *)
    apply (no_rational_sqrt2 a).
    assert (Hbb : b * b == 0) by (rewrite Hb0; ring).
    lra.
Qed.

