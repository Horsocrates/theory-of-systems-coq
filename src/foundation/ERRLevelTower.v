(* ===================================================================== *)
(*  The iterated lift and the climbing level                               *)
(* ===================================================================== *)

(** The level climbed n steps up. *)
Fixpoint lvl_iter (n : nat) (L : Level) : Level :=
  match n with
  | O => L
  | Datatypes.S k => LS (lvl_iter k L)
  end.

(** The system lifted n levels up — the SAME triad, climbing the hierarchy. *)
Fixpoint lift_iter (n : nat) {L : Level} (Sys : FunctionalSystem L)
  : FunctionalSystem (lvl_iter n L) :=
  match n with
  | O => Sys
  | Datatypes.S k => fs_lift (lift_iter k Sys)
  end.

(* ===================================================================== *)
(*  The carrier is invariant; the level strictly climbs                    *)
(* ===================================================================== *)

(** ★★ The carrier is preserved through the WHOLE tower: one system, climbing levels. *)
Lemma lift_iter_elements : forall (n : nat) {L} (Sys : FunctionalSystem L),
  get_Elements (lift_iter n Sys) = get_Elements Sys.
Proof.
  intros n. induction n as [|k IH]; intros L Sys.
  - reflexivity.
  - exact (eq_trans (lift_elements (lift_iter k Sys)) (IH L Sys)).
Qed.

(** ★ Each step climbs exactly one level. *)
Lemma tower_climbs : forall (n : nat) (L : Level),
  level_depth (lvl_iter (Datatypes.S n) L) = Datatypes.S (level_depth (lvl_iter n L)).
Proof. intros n L. reflexivity. Qed.

(** The depth after n steps = n + the base depth. *)
Lemma lvl_iter_depth : forall (n : nat) (L : Level),
  level_depth (lvl_iter n L) = n + level_depth L.
Proof.
  intros n. induction n as [|k IH]; intro L.
  - reflexivity.
  - simpl. rewrite IH. reflexivity.
Qed.

(** Every level has positive (finite, ≥ 1) depth. *)
Lemma level_depth_pos : forall L, 1 <= level_depth L.
Proof. induction L; simpl; lia. Qed.

(* ===================================================================== *)
(*  No completed tower (P4)                                                *)
(* ===================================================================== *)

(** ★★ The tower is UNBOUNDED: it exceeds the depth of any given level. *)
Lemma tower_unbounded : forall {L} (m : nat),
  exists n, m < level_depth (lvl_iter n L).
Proof.
  intros L m. exists (Datatypes.S m). rewrite lvl_iter_depth.
  pose proof (level_depth_pos L). lia.
Qed.

(** ★★★ NO COMPLETED TOWER: there is no level M bounding all stages of the tower — so the tower has
    no colimit object in the hierarchy.  This is P4 (no completed infinity of levels): Level is
    inductively generated (LS, no limit level), so the ascending tower is a genuine PROCESS, never a
    finished object.  The unbounded depth is the role-limit side of H1; each finite stage (with its
    fixed carrier) is the Element side. *)
Lemma no_completed_tower : forall {L},
  ~ exists M : Level, forall n, level_depth (lvl_iter n L) <= level_depth M.
Proof.
  intros L [M HM].
  destruct (tower_unbounded (L:=L) (level_depth M)) as [n Hn].
  specialize (HM n). lia.
Qed.

