(** ★★★ THE LEVEL TOWER IS A PROCESS, NOT A COMPLETED OBJECT.
      (carrier)    the carrier is invariant through the whole tower — one system climbing;
      (climbs)     each step adds exactly one level;
      (unbounded)  the tower exceeds the depth of any given level;
      (no colimit) no level bounds all stages — the completed tower does not exist (P4).
    The full-embedding functor (ERRLevelFunctor) iterated gives an ascending ω-chain with the same
    carrier and strictly increasing level, which NEVER completes: P4 (no limit level) = H1 (the
    completed tower is the unattained role-limit; each finite stage is the actual Element side). *)
Theorem err_level_tower :
  (forall (n : nat) (L : Level) (Sys : FunctionalSystem L),
     get_Elements (lift_iter n Sys) = get_Elements Sys)
  /\ (forall (n : nat) (L : Level),
        level_depth (lvl_iter (Datatypes.S n) L) = Datatypes.S (level_depth (lvl_iter n L)))
  /\ (forall (L : Level) (m : nat), exists n, m < level_depth (lvl_iter n L))
  /\ (forall (L : Level), ~ exists M : Level, forall n, level_depth (lvl_iter n L) <= level_depth M).
Proof.
  split; [ | split; [ | split ] ].
  - intros n L Sys. exact (@lift_iter_elements n L Sys).
  - intros n L. exact (tower_climbs n L).
  - intros L m. exact (@tower_unbounded L m).
  - intros L. exact (@no_completed_tower L).
Qed.

