Local Open Scope nat_scope.

(** The geometric interval = the NUMBER of points the causal order puts strictly between two events
    = proper time (CausalOrderGeometry).  Computed FROM the order, not given. *)
Definition interval_card (lo hi : nat) : nat := hi - lo - 1.

(** ★ The geometric datum is COMPUTED from the order positions. *)
Lemma geometry_from_order : interval_card 0 4 = 3.
Proof. reflexivity. Qed.

(** ★ The geometry TRACKS the relational data: a different order gives a different geometry
    (no fixed stage — the geometry is generated by order+number). *)
Lemma geometry_tracks_order : interval_card 0 4 <> interval_card 0 2.
Proof. discriminate. Qed.

