Open Scope Q_scope.

(** The metric between two Roles (direction-vectors in Q^3) = their symmetric inner product
    = the Sym^2(Roles) pairing (H3).  It takes the Roles as INPUT — no Roles, no metric. *)
Definition metric (a b c x y z : Q) : Q := a*x + b*y + c*z.

(** ★ The metric is SYMMETRIC (Sym^2, the Rule of mutual measurement). *)
Lemma metric_symmetric : forall a b c x y z, metric a b c x y z == metric x y z a b c.
Proof. intros. unfold metric. ring. Qed.

(** ★ BACKGROUND INDEPENDENCE (i): the metric genuinely DEPENDS on the Roles —
    <e1,e1> = 1 but <e1,e2> = 0, so the metric tracks the role-data, it is not blind/constant. *)
Lemma metric_depends_on_roles :
  ~ (metric 1 0 0 1 0 0 == metric 1 0 0 0 1 0).
Proof. unfold metric. lra. Qed.

(** ★★ BACKGROUND INDEPENDENCE (ii): the relational metric is NOT any fixed background constant k —
    no constant function can equal it, because it varies with the Roles.  The metric is constituted
    from the Roles, never a pre-given stage. *)
Lemma relational_not_fixed_background : forall k : Q,
  ~ (forall a b c x y z, metric a b c x y z == k).
Proof.
  intros k H.
  pose proof (H 1 0 0 1 0 0) as H1.   (* metric e1 e1 == k  i.e. 1 == k *)
  pose proof (H 1 0 0 0 1 0) as H2.   (* metric e1 e2 == k  i.e. 0 == k *)
  unfold metric in H1, H2. lra.
Qed.

