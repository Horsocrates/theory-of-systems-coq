(** wqo над разрешимым/ℕ-измеримым — НЕ стена, а процесс:
      -- базовый рунг: ℕ — wqo, минимально-плохая невозможна (0-ax спуск, wqo_nat_le);
      -- замыкание: монотонная ℕ-мера, отражающая порядок => wqo (0-ax, как процесс);
      -- метод: минимально-плохой выбор над разрешимым порядком = детерм. процесс (0-ax, без DC).
    Полный Крускал (произвольные деревья: Higman на произв. алфавитах + общая минимально-плохая) —
    consistency-strength ГОРИЗОНТ-ПОДЪЁМ выше, локализованный разрешимостью, а НЕ стена. *)
Theorem wqo_is_process_over_decidable :
  is_wqo Nat.le
  /\ (forall f : nat -> nat, ~ bad_seq Nat.le f)
  /\ (forall (A : Type) (le : A -> A -> Prop) (h : A -> nat),
        (forall a b : A, (h a <= h b)%nat -> le a b) -> is_wqo le)
  /\ (forall (R : nat -> nat -> bool) (Htot : forall x, exists y, R x y = true) (x0 n : nat),
        R (dc_chain R Htot x0 n) (dc_chain R Htot x0 (S n)) = true).
Proof.
  split; [ exact wqo_nat_le | ].
  split; [ exact no_bad_seq_nat | ].
  split.
  - intros A le h Href. exact (wqo_pullback_nat le h Href).
  - intros R Htot x0 n. apply dc_chain_step.
Qed.
