From Stdlib Require Import PeanoNat Arith Lia.
From ToS Require Import settheory.KruskalTree.               (* is_wqo, wqo_nat_le *)
From ToS Require Import cs.CountableDependentChoiceFree.      (* next, dc_chain, dc_chain_step, next_least *)

(* ===================================================================== *)
(*  Базовый рунг: над ℕ плохой последовательности нет (0-ax процесс)        *)
(* ===================================================================== *)

(** Плохая последовательность: нет ни одной good-пары (i<j с le (f i) (f j)). *)
Definition bad_seq {A : Type} (le : A -> A -> Prop) (f : nat -> A) : Prop :=
  forall i j : nat, (i < j)%nat -> ~ le (f i) (f j).

(** Над ℕ плохой последовательности НЕ существует — прямо из wqo_nat_le (фундированный спуск, 0-ax).
    Это и есть «минимально-плохая последовательность невозможна над ℕ», как завершающийся процесс. *)
Lemma no_bad_seq_nat : forall f : nat -> nat, ~ bad_seq Nat.le f.
Proof.
  intros f Hbad. destruct (wqo_nat_le f) as [i [j [Hij Hle]]].
  apply (Hbad i j Hij). exact Hle.
Qed.

(* ===================================================================== *)
(*  Замыкание: монотонная ℕ-мера, отражающая порядок => wqo (как процесс)   *)
(* ===================================================================== *)

(** Если h : A -> nat отражает порядок (h a <= h b => le a b), то le — wqo: good-пара находится
    спуском wqo_nat_le по (h ∘ f).  Тот же приём, что depth1_wqo (num_children) в KruskalFull —
    разрешимая ℕ-измеримая часть, достигнутая КАК ПРОЦЕСС. *)
Theorem wqo_pullback_nat {A : Type} (le : A -> A -> Prop) (h : A -> nat) :
  (forall a b : A, (h a <= h b)%nat -> le a b) -> is_wqo le.
Proof.
  intros Hrefl f. destruct (wqo_nat_le (fun n => h (f n))) as [i [j [Hij Hle]]].
  exists i, j. split; [ exact Hij | ]. apply Hrefl. exact Hle.
Qed.

(** Конкретно: пары, сравниваемые по первой координате, — wqo (0-ax, через ℕ-меру fst). *)
Example wqo_pairs_by_fst : is_wqo (fun p q : nat * nat => (fst p <= fst q)%nat).
Proof. apply (wqo_pullback_nat _ (fun p => fst p)). intros a b H. exact H. Qed.

(* ===================================================================== *)
(*  Метод: минимально-плохой выбор над разрешимым = процесс (без DC)        *)
(* ===================================================================== *)

(** Классический аргумент Нэша–Уильямса берёт на каждом шаге минимальное плохое продолжение —
    за это классике нужен Dependent Choice.  Над РАЗРЕШИМЫМ тотальным R этот выбор есть
    детерминированный процесс наименьшего-преемника dc_chain (cs/CountableDependentChoiceFree):
      -- это R-цепь (шаг всегда валиден),  и
      -- каждый шаг МИНИМАЛЕН (наименьший допустимый преемник),
    — каноничен, единствен, 0-ax, БЕЗ всякого DC.  (Мост-переупаковка для wqo-нарратива.) *)
Theorem minimal_selection_is_process :
  forall (R : nat -> nat -> bool) (Htot : forall x, exists y, R x y = true) (x0 : nat),
    (forall n, R (dc_chain R Htot x0 n) (dc_chain R Htot x0 (S n)) = true)
    /\ (forall x y, R x y = true -> next R Htot x <= y).
Proof.
  intros R Htot x0. split.
  - intro n. apply dc_chain_step.
  - apply next_least.
Qed.

