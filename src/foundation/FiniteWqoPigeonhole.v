From Stdlib Require Import Bool.

(** Конечное голубятное ядро wqo: среди трёх булевых значений два совпадают — «хорошая пара». *)
Lemma bool_pigeonhole3 : forall a b c : bool, a = b \/ b = c \/ a = c.
Proof.
  intros a b c; destruct a, b, c;
    first [ left; reflexivity
          | right; left; reflexivity
          | right; right; reflexivity ].
Qed.
